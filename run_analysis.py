"""
Run every question in sql/04_analysis.sql against data/raw/*.csv with DuckDB
(no database server needed) and write the answers to results/results.md.

    python data/generate.py     # once, if data/raw is empty
    python run_analysis.py

The SQL is written for PostgreSQL; DuckDB runs the same queries unchanged.
"""

from __future__ import annotations

import re
import time
from pathlib import Path

import duckdb

ROOT = Path(__file__).parent
RAW = ROOT / "data" / "raw"
TABLES = ["category", "products", "stores", "sales", "warranty"]


def load(con: duckdb.DuckDBPyConnection) -> None:
    for t in TABLES:
        con.execute(f"CREATE OR REPLACE TABLE {t} AS SELECT * FROM read_csv_auto('{RAW / (t + '.csv')}', header = true)")
    con.execute("ALTER TABLE products ALTER COLUMN price TYPE DECIMAL(10, 2)")


def questions(sql: str) -> list[tuple[str, str, str]]:
    """Split the analysis file into (id, title, query) using the '-- Qnn:' headers."""
    parts = re.split(r"^-- (Q\d{2}): (.+)$", sql, flags=re.M)
    out = []
    for i in range(1, len(parts), 3):
        query = re.sub(r"^\s*--.*$", "", parts[i + 2], flags=re.M).strip()
        out.append((parts[i], parts[i + 1].strip(), query.rstrip(";")))
    return out


PLAIN = {"year", "quarter", "rnk"}  # integers shown without thousands separators


def to_markdown(cols: list[str], rows: list[tuple]) -> str:
    def fmt(col: str, v):
        if v is None:
            return "–"
        if isinstance(v, float):
            return f"{v:,.1f}"
        if isinstance(v, int) and col not in PLAIN:
            return f"{v:,}"
        return str(v)

    head = "| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n"
    return head + "\n".join("| " + " | ".join(fmt(c, v) for c, v in zip(cols, r)) + " |" for r in rows)


def main() -> None:
    if not (RAW / "sales.csv").exists():
        raise SystemExit("data/raw/sales.csv not found. Run: python data/generate.py")
    con = duckdb.connect()
    load(con)
    counts = {t: con.execute(f"SELECT COUNT(*) FROM {t}").fetchone()[0] for t in TABLES}

    md = ["# Results\n", "Generated by `run_analysis.py` from `sql/04_analysis.sql`.\n",
          "Row counts: " + ", ".join(f"{t} {n:,}" for t, n in counts.items()) + "\n"]
    for qid, title, query in questions((ROOT / "sql" / "04_analysis.sql").read_text()):
        t0 = time.perf_counter()
        res = con.execute(query)
        cols = [d[0] for d in res.description]
        rows = res.fetchall()
        ms = (time.perf_counter() - t0) * 1000
        print(f"{qid}  {len(rows):>3} rows  {ms:7.1f} ms  {title}")
        md.append(f"## {qid}. {title}\n\n{to_markdown(cols, rows)}\n")

    out = ROOT / "results" / "results.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(md))
    print(f"\nwrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
